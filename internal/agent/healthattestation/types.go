// Package healthattestation authenticates bounded external reference-client
// reports against a durable, single-use nonce. It does NOT run reference
// clients, qualify public M0, attest host installation or authorize APPLIED.
package healthattestation

import (
	"crypto/ed25519"
	"encoding/json"
	"errors"
	"regexp"
	"time"
)

const (
	MaxEvidenceBytes            = 8192
	signatureDomain             = "omnipanel:external-health:ed25519-v2\n"
	protocolVersion             = "external-health-v2"
	maxPendingChallenges        = 64
	maxWitnessTTL               = 2 * time.Minute
	maxSafeSequence      uint64 = 9007199254740991
)

var (
	ErrEvidenceRejected  = errors.New("external witness evidence, trust or durable nonce rejected")
	witnessUUIDPattern   = regexp.MustCompile(`^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$`)
	witnessIDPattern     = regexp.MustCompile(`^[a-z][a-z0-9-]{0,63}$`)
	witnessDigestPattern = regexp.MustCompile(`^[a-f0-9]{64}$`)
	witnessRefPattern    = regexp.MustCompile(`^sha256:[a-f0-9]{64}$`)
)

// Scope is pinned by trusted local provisioning after the exact signed
// manifest, qualified candidate generation and external test profile are
// reviewed. A witness cannot choose or change this scope with its response.
type Scope struct {
	NodeID             string `json:"nodeId"`
	Epoch              string `json:"epoch"`
	StructuralSequence uint64 `json:"structuralSequence"`
	MembershipSequence uint64 `json:"membershipSequence"`
	ManifestDigest     string `json:"manifestDigest"`
	Generation         string `json:"generation"`
	ProfileDigest      string `json:"profileDigest"`
}

func (s Scope) valid() bool {
	return witnessUUIDPattern.MatchString(s.NodeID) &&
		witnessUUIDPattern.MatchString(s.Epoch) &&
		s.StructuralSequence > 0 && s.StructuralSequence <= maxSafeSequence &&
		s.MembershipSequence <= maxSafeSequence &&
		witnessDigestPattern.MatchString(s.ManifestDigest) &&
		witnessRefPattern.MatchString(s.Generation) &&
		witnessRefPattern.MatchString(s.ProfileDigest)
}

// Config must be supplied by the separately trusted verifier service. The
// Ed25519 witness public key is never accepted from an evidence report or a
// node-provided URL. Its corresponding private key must live on an independent
// reference-client machine, not on the target VPS or control API.
type Config struct {
	Path       string
	Scope      Scope
	WitnessID  string
	WitnessKey ed25519.PublicKey
	TTL        time.Duration
	Now        func() time.Time
}

// Challenge is generated by the trusted verifier after a candidate becomes
// eligible for external testing. An actual externally executed test runner,
// not this package, must perform the connection and protected-egress probes.
type Challenge struct {
	Version         string `json:"version"`
	Scope           Scope  `json:"scope"`
	Nonce           string `json:"nonce"`
	WitnessID       string `json:"witnessId"`
	IssuedAtMillis  int64  `json:"issuedAtMillis"`
	ExpiresAtMillis int64  `json:"expiresAtMillis"`
}

// Observations are CLAIMS by an external signer, not an independent proof of
// actual network execution. Public M0 requires reviewing a real transcript
// and independently establishing the tester's machine/network provenance.
type Observations struct {
	RealityVisionOK     bool   `json:"realityVisionOk"`
	BytesSent           uint64 `json:"bytesSent"`
	BytesReceived       uint64 `json:"bytesReceived"`
	ProtectedIPv4Denied bool   `json:"protectedIpv4Denied"`
	ProtectedIPv6Denied bool   `json:"protectedIpv6Denied"`
	MetadataDenied      bool   `json:"metadataDenied"`
	DNSRebindingDenied  bool   `json:"dnsRebindingDenied"`
	TranscriptDigest    string `json:"transcriptDigest"`
}

type Evidence struct {
	Challenge        Challenge    `json:"challenge"`
	RunID            string       `json:"runId"`
	ObservedAtMillis int64        `json:"observedAtMillis"`
	Observations     Observations `json:"observations"`
	Signature        string       `json:"signature"`
}

// Accepted reports only cryptographically authenticated claims and a durable,
// consumed challenge. It MUST NOT be used as a public M0 qualification or a
// local applied-state receipt.
type Accepted struct {
	Scope            Scope
	Nonce            string
	RunID            string
	WitnessID        string
	EvidenceDigest   string
	ObservedAtMillis int64
}

// SigningBytes defines the exact v2 signing contract. The report's Signature
// field is encoded as an empty string, then prefixed with a separate domain.
// Canonical field ordering and JSON escaping follow Go encoding/json; wire
// verification requires byte-identical canonical report encoding.
func SigningBytes(e Evidence) ([]byte, error) {
	e.Signature = ""
	raw, err := json.Marshal(e)
	if err != nil || len(raw) == 0 || len(raw) > MaxEvidenceBytes {
		return nil, ErrEvidenceRejected
	}
	return append([]byte(signatureDomain), raw...), nil
}
